  const LOCALES = { es: 'es-CO', en: 'en-US', pt: 'pt-BR' };
  let current = 'es';

  function detect() {
    try {
      const saved = localStorage.getItem('nfsu2-lang');
      if (saved && STRINGS[saved]) return saved;
    } catch (_) { /* almacenamiento no disponible */ }
    const nav = (navigator.languages || [navigator.language || 'es']).map((l) => l.slice(0, 2));
    return nav.find((l) => STRINGS[l]) || 'es';
  }

  function t(key, vars) {
    let s = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.es[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
    return s;
  }

  function setLang(lang) {
    if (!STRINGS[lang]) return;
    current = lang;
    try { localStorage.setItem('nfsu2-lang', lang); } catch (_) { /* ignorar */ }
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.title = t('title');
  }

  const fmt = (n) => Number(n).toLocaleString(LOCALES[current] || undefined);

  root.I18N = { STRINGS, t, setLang, detect, fmt, get lang() { return current; } };
